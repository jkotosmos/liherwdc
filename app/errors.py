"""Базовые исключения.

Отдельный модуль без зависимостей: и слой инструментов, и слой интеграций
импортируют исключения отсюда, поэтому между ними нет циклической связи.
"""

from __future__ import annotations


class ToolError(Exception):
    """Ожидаемая ошибка инструмента: возвращается модели как is_error."""


class IntegrationUnavailable(ToolError):
    """Интеграция не настроена (нет токена, нет библиотеки, нет доступа)."""
